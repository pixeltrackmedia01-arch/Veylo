// Generates supabase/catalogue.sql from supabase/catalogue/cars.mjs.
// The SQL is idempotent: re-running it updates models, variants and prices in place.
// Data travels as one compact JSON document; specifications and indicative feature
// lists are expanded in SQL so the file stays small enough to paste into a SQL editor.
import { writeFileSync } from "node:fs";
import { BRANDS, CARS, SOURCE, VERIFIED_AT } from "../supabase/catalogue/cars.mjs";

const toData = (cars) => ({
  brands: Object.values(BRANDS).map((b) => ({ name: b.name, slug: b.slug, website: b.website })),
  cars: cars.map((c) => ({
    brand: BRANDS[c.brand].slug,
    warranty: BRANDS[c.brand].warranty,
    model: c.model,
    slug: c.slug,
    body: c.body,
    popularity: c.popularity,
    summary: c.summary,
    highlights: c.highlights,
    dims: c.dims,
    colours: c.colours.map(([name, hex]) => ({ name, hex })),
    variants: c.variants.map(([name, slug, fuel, trans, cc, power, torque, mileage, price, tier, extra]) => ({
      name, slug, fuel, trans, cc, power, torque, price, tier,
      mileage: fuel === "electric" ? null : typeof mileage === "number" ? `${mileage} kmpl` : mileage,
      battery: extra?.battery ?? null,
      range: extra?.range ?? null,
    })),
  })),
});

const render = (data) => `-- GENERATED by scripts/build-catalogue-sql.mjs from supabase/catalogue/cars.mjs. Do not edit by hand.
-- Indicative car catalogue: models, variants, specifications, feature lists and Surat price references.

-- Indicative feature list by trim tier (1 base, 2 mid, 3 top). Exact equipment varies by variant.
create or replace function pg_temp.gd_features(p_tier int, p_airbags int, p_big boolean)
returns jsonb language sql immutable as $f$
  select jsonb_build_object(
    'Safety', to_jsonb(array_remove(array[
      case when p_airbags is not null then p_airbags || ' airbags' end,
      'ABS with EBD', 'Rear parking sensors', 'ISOFIX child-seat mounts', 'Seat-belt reminders (all seats)',
      case when p_tier >= 2 then 'Electronic stability control' end,
      case when p_tier >= 2 then 'Hill-hold assist' end,
      case when p_tier >= 2 then 'Rear-view camera' end,
      case when p_tier >= 3 then 'Tyre-pressure monitoring' end], null)),
    'Comfort', to_jsonb(array_remove(array[
      'Air conditioning', 'Power steering', 'Front power windows', 'Height-adjustable driver seat',
      case when p_tier >= 2 then 'All four power windows' end,
      case when p_tier >= 2 then 'Electrically adjustable ORVMs' end,
      case when p_tier >= 2 then 'Steering-mounted controls' end,
      case when p_tier >= 2 and p_big then 'Rear AC vents' end,
      case when p_tier >= 3 then 'Automatic climate control' end,
      case when p_tier >= 3 then 'Keyless entry & push-button start' end,
      case when p_tier >= 3 then 'Cruise control' end,
      case when p_tier >= 3 then 'Wireless phone charger' end], null)),
    'Exterior', to_jsonb(array_remove(array[
      'Halogen headlamps', 'Body-coloured bumpers',
      case when p_tier >= 2 then 'LED DRLs' end,
      case when p_tier = 2 then 'Wheel covers / alloy wheels (variant-dependent)' end,
      case when p_tier >= 3 then 'LED headlamps' end,
      case when p_tier >= 3 then 'Alloy wheels' end,
      case when p_tier >= 3 then 'Sunroof (where offered)' end], null)),
    'Infotainment', to_jsonb(array_remove(array[
      'Bluetooth audio', 'USB charging',
      case when p_tier >= 2 then 'Touchscreen infotainment' end,
      case when p_tier >= 2 then 'Android Auto & Apple CarPlay' end,
      case when p_tier >= 2 then '4+ speakers' end,
      case when p_tier >= 3 then 'Connected-car features' end,
      case when p_tier >= 3 then 'Digital instrument cluster' end], null)))
$f$;

do $catalogue$
declare
  d jsonb := ${"$json$"}${JSON.stringify(data)}${"$json$"};
  v_source text := ${"$s$"}${SOURCE}${"$s$"};
  v_verified date := '${VERIFIED_AT}';
  v_city uuid; v_mfr uuid; v_vehicle uuid; v_variant uuid;
  b jsonb; c jsonb; v jsonb; dm jsonb; i int; v_price numeric; v_ev boolean; v_specs jsonb;
begin
  select id into v_city from public.cities where slug = 'surat';
  if v_city is null then raise exception 'Surat city row missing'; end if;

  for b in select * from jsonb_array_elements(d->'brands') loop
    insert into public.manufacturers (name, slug, categories, website_url)
    values (b->>'name', b->>'slug', '{car}', b->>'website')
    on conflict (slug) do update set website_url = excluded.website_url, is_active = true;
  end loop;

  for c in select * from jsonb_array_elements(d->'cars') loop
    dm := c->'dims';
    select id into v_mfr from public.manufacturers where slug = c->>'brand';
    insert into public.vehicles (manufacturer_id, model_name, slug, category, body_type, description, summary,
      highlights, colours, warranty, popularity, status, is_demo, published_at)
    values (v_mfr, c->>'model', c->>'slug', 'car', c->>'body', c->>'summary', c->>'summary',
      array(select jsonb_array_elements_text(c->'highlights')), c->'colours', c->>'warranty',
      (c->>'popularity')::int, 'published', false, now())
    on conflict (slug) do update set body_type = excluded.body_type, description = excluded.description,
      summary = excluded.summary, highlights = excluded.highlights, colours = excluded.colours,
      warranty = excluded.warranty, popularity = excluded.popularity, status = 'published', is_demo = false,
      published_at = coalesce(public.vehicles.published_at, now())
    returning id into v_vehicle;

    i := 0;
    for v in select * from jsonb_array_elements(c->'variants') loop
      v_ev := v->>'fuel' = 'electric';
      v_specs := jsonb_strip_nulls(jsonb_build_object(
        'Battery', v->>'battery', 'Range', v->>'range',
        'Max power', v->>'power', 'Max torque', v->>'torque', 'Mileage', v->>'mileage',
        'Seating', (dm->>'seats') || ' seats',
        'Length', (dm->>'l') || ' mm', 'Width', (dm->>'w') || ' mm', 'Height', (dm->>'h') || ' mm',
        'Wheelbase', (dm->>'wb') || ' mm',
        'Fuel tank', (dm->>'tank') || ' litres', 'Boot space', (dm->>'boot') || ' litres',
        'Airbags', dm->>'airbags'));
      insert into public.vehicle_variants (vehicle_id, name, slug, fuel_type, transmission, engine_cc,
        specifications, features, specs_source, specs_verified_at, status, sort_order)
      values (v_vehicle, v->>'name', v->>'slug', v->>'fuel', v->>'trans', (v->>'cc')::int, v_specs,
        pg_temp.gd_features((v->>'tier')::int, (dm->>'airbags')::int, c->>'body' in ('suv', 'muv')),
        'Manufacturer-claimed specifications (indicative)', v_verified, 'published', i)
      on conflict (vehicle_id, slug) do update set name = excluded.name, fuel_type = excluded.fuel_type,
        transmission = excluded.transmission, engine_cc = excluded.engine_cc,
        specifications = excluded.specifications, features = excluded.features,
        specs_source = excluded.specs_source, specs_verified_at = excluded.specs_verified_at,
        status = 'published', sort_order = excluded.sort_order
      returning id into v_variant;

      -- Indicative Surat on-road estimate: Gujarat one-time road tax 6% (EV exemption assumed),
      -- first-year comprehensive insurance estimate, and registration/plates/FASTag.
      v_price := (v->>'price')::numeric;
      update public.vehicle_prices set is_current = false
       where variant_id = v_variant and city_id = v_city and is_current;
      insert into public.vehicle_prices (variant_id, city_id, ex_showroom, registration_road_tax, insurance,
        other_charges, price_kind, source, verified_at, is_current, is_demo, notes)
      values (v_variant, v_city, v_price,
        case when v_ev then 0 else round(v_price * 0.06) end,
        round(v_price * case when v_ev then 0.03 else 0.035 end / 100) * 100,
        5000, 'indicative', v_source, v_verified, true, false,
        'On-road estimate: Gujarat road tax' || case when v_ev then ' (EV exemption assumed)' else ' 6%' end
          || ', indicative first-year insurance, registration & FASTag. Confirm with the dealer.');
      i := i + 1;
    end loop;
  end loop;
end
$catalogue$;
`;

writeFileSync(new URL("../supabase/catalogue.sql", import.meta.url), render(toData(CARS)));

// Optional: smaller chunks for SQL editors / tools with request-size limits.
const chunks = Number(process.argv[2] ?? 0);
for (let n = 0; n < chunks; n++) {
  const size = Math.ceil(CARS.length / chunks);
  const path = process.env.CHUNK_DIR ?? ".";
  writeFileSync(`${path}/catalogue-${n + 1}.sql`, render(toData(CARS.slice(n * size, (n + 1) * size))));
}
console.log(`Wrote supabase/catalogue.sql: ${CARS.length} models, ${CARS.reduce((n, c) => n + c.variants.length, 0)} variants.`);
